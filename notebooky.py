def posicao_falsa(a, b, max_iter=7):
    iteracoes = []
    for k in range(1, max_iter + 1):
        fa, fb = f(a), f(b)
        x = (a * fb - b * fa) / (fb - fa)
        fx = f(x)
        iteracoes.append({"k": k, "a_k": a, "b_k": b, "f(a_k)": fa, "f(b_k)": fb, "x_k": x, "f(x_k)": fx})
        if fa * fx < 0:
            b = x
        else:
            a = x
    return pd.DataFrame(iteracoes)

