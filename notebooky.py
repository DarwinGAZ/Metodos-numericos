import math
import matplotlib.pyplot as plt
import pandas as pd

def f(x):
    return (900 - x**2)**(-0.5) + (400 - x**2)**(-0.5) - 0.125

def df(x):
    return (x / (900 - x**2)**(1.5)) + (x / (400 - x**2)**(1.5))

def newton_raphson(x0, max_iter=4):
    iteracoes = []
    x_k = x0
    for k in range(max_iter):
        fx, dfx = f(x_k), df(x_k)
        x_next = x_k - (fx / dfx)
        erro = abs(x_next - x_k)
        iteracoes.append({"k": k, "x_k": x_k, "f(x_k)": fx, "f'(x_k)": dfx, "x_{k+1}": x_next, "|x_{k+1} - x_k|": erro})
        x_k = x_next
    return pd.DataFrame(iteracoes)

df_newton = newton_raphson(15.0, max_iter=4)

print("=== MÉTODO DE NEWTON-RAPHSON ===")
display(df_newton.style.format("{:.6f}", subset=["x_k", "f(x_k)", "f'(x_k)", "x_{k+1}", "|x_{k+1} - x_k|"]))

plt.figure(figsize=(8, 4))
plt.plot(df_newton["k"], df_newton["x_k"], 'p-', color='#d62728', linewidth=2, label='x_k')
plt.axhline(y=16.2121, color='black', linestyle='--', alpha=0.7, label='Valor Exato (~16.2121 m)')
plt.title('Convergência Quadrática - Newton-Raphson', fontsize=12, fontweight='bold')
plt.xlabel('Iteração (k)')
plt.ylabel('Largura x (m)')
plt.grid(True, linestyle=':', alpha=0.6)
plt.legend()
