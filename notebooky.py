import math
import matplotlib.pyplot as plt
import pandas as pd

def f(x):
    return (1 / math.sqrt(900 - x**2)) + (1 / math.sqrt(400 - x**2)) - 0.125

def bissecao(a, b, tol=0.01):
    iteracoes = []
    k = 1

    while (b - a) >= tol:
        x = (a + b) / 2.0
        fx = f(x)
        iteracoes.append({
            "k": k, "a": a, "b": b, "x = (a+b)/2": x,
            "f(x)": fx, "b - a": b - a, "Novo Intervalo": f"[{a:.6f}; {b:.6f}]"
        })
        if f(a) * fx < 0:
            b = x
        else:
            a = x
        k += 1

    x = (a + b) / 2.0
    fx = f(x)
    iteracoes.append({
        "k": k, "a": a, "b": b, "x = (a+b)/2": x,
        "f(x)": fx, "b - a": b - a, "Novo Intervalo": f"[{a:.6f}; {b:.6f}]"
    })
    return pd.DataFrame(iteracoes)

df_bissecao = bissecao(16.0, 17.0, tol=0.01)

print("=== MÉTODO DA BISSEÇÃO ===")
display(df_bissecao.style.format({
    "a": "{:.6f}", "b": "{:.6f}", "x = (a+b)/2": "{:.6f}",
    "f(x)": "{:.6f}", "b - a": "{:.6f}"
}))

plt.figure(figsize=(8, 4))
plt.plot(df_bissecao["k"], df_bissecao["x = (a+b)/2"], 'o-', color='#1f77b4', linewidth=2, label='x_k')
plt.axhline(y=16.2121, color='r', linestyle='--', alpha=0.7, label='Valor Exato (~16.2121 m)')
plt.title('Convergência - Método da Bisseção', fontsize=12, fontweight='bold')
plt.xlabel('Iteração (k)')
plt.ylabel('Largura x (m)')
plt.grid(True, linestyle=':', alpha=0.6)
plt.legend()
plt.show()

