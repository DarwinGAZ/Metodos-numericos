import math
import matplotlib.pyplot as plt
import pandas as pd

def f(x):
    return (900 - x**2)**(-0.5) + (400 - x**2)**(-0.5) - 0.125

def secantes(x0, x1, max_iter=6):
    iteracoes = []
    iteracoes.append({"k": 0, "x_k": x0, "f(x_k)": f(x0), "x_{k+1}": x1, "|x_{k+1} - x_k|": abs(x1 - x0)})
    for k in range(1, max_iter):
        fx0, fx1 = f(x0), f(x1)
        x_next = x1 - fx1 * ((x1 - x0) / (fx1 - fx0))
        erro = abs(x_next - x1)
        iteracoes.append({"k": k, "x_k": x1, "f(x_k)": fx1, "x_{k+1}": x_next, "|x_{k+1} - x_k|": erro})
        x0, x1 = x1, x_next
    return pd.DataFrame(iteracoes)

