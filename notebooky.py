import math
import matplotlib.pyplot as plt
import pandas as pd

def a_func(x):
    return math.sqrt(900 - x**2)

def b_func(x):
    return (0.125 - (900 - x**2)**(-0.5))**(-1)

def g(x):
    return math.sqrt(400 - (b_func(x))**2)

def ponto_fixo(x0, max_iter=6):
    iteracoes = []
    x_k = x0
    for k in range(max_iter):
        a_k, b_k = a_func(x_k), b_func(x_k)
        x_next = g(x_k)
        erro = abs(x_next - x_k)
        iteracoes.append({"k": k, "x_k": x_k, "a(x_k)": a_k, "b(x_k)": b_k, "x_{k+1}": x_next, "|x_{k+1} - x_k|": erro})
        x_k = x_next
    return pd.DataFrame(iteracoes)

df_ponto_fixo = ponto_fixo(15.0, max_iter=6)

